"""The daily brief and run summary.

Written for a human editor to read over coffee. It leads with what moved and
why it might matter, and it states plainly where the data was missing -- an
honest gap is more useful than a confident-looking number.

Explicitly NOT one video per signal. Most signals are context.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

from ..db import Database
from ..models import ConceptMetrics
from .discovery import DiscoveryResult


def _momentum_words(value: float) -> str:
    if value >= 0.45:
        return "High"
    if value >= 0.30:
        return "Moderate"
    if value >= 0.18:
        return "Early"
    return "Low"


def _key_sources(db: Database, concept_id: int, limit: int = 3) -> list[str]:
    # DISTINCT on the item: one essay mentioning a concept nine times is one
    # source, not nine.
    rows = db.conn.execute(
        "SELECT DISTINCT s.id, s.title, s.url, s.source_name, s.published_at"
        " FROM concept_mentions m JOIN source_items s ON s.id = m.source_item_id"
        " WHERE m.concept_id = ? AND s.url IS NOT NULL"
        "   AND COALESCE(s.title,'') NOT IN ('[dead]','[flagged]','[deleted]')"
        " GROUP BY s.id"
        " ORDER BY s.published_at DESC LIMIT ?",
        (concept_id, limit),
    ).fetchall()
    return [
        f"[{(r['title'] or r['source_name'])[:80]}]({r['url']}) "
        f"— {r['source_name']}, {str(r['published_at'])[:10]}"
        for r in rows
    ]


def write_daily_brief(
    db: Database, result: DiscoveryResult, runs_dir: Path, *, signal_count: int = 12
) -> Path:
    """Render data/runs/<run_id>/daily_brief.md."""
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    out_dir = runs_dir / result.run_id
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "daily_brief.md"

    lines: list[str] = [f"# Frontier Scout Daily Brief — {today}", ""]

    # Honest header about what the run could and could not see.
    if not result.llm_available:
        lines.append(
            "> **Quantitative run only.** No `ANTHROPIC_API_KEY` was configured, "
            "so this brief reports measured movement without editorial "
            "interpretation. Nothing below was generated by a model."
        )
        lines.append("")
    if result.notes:
        for note in result.notes:
            lines.append(f"> {note}")
        lines.append("")

    # Editor-approved concepts are the brief. Auto-nominated phrases are a
    # separate section: they are suggestions, and mixing them in would let a
    # thin n-gram headline the day's intelligence.
    tracked = [m for m in result.metrics if m.status == "tracked"]
    nominated = [m for m in result.metrics if m.status != "tracked"]

    lines.append(
        f"Tracking {len(tracked)} concepts across {len(result.groups)} groups"
        + (f", plus {len(nominated)} auto-nominated phrases awaiting review" if nominated else "")
        + ". Not every signal deserves a video — most are context."
    )
    lines.append("")

    # -- the signals ------------------------------------------------------
    lines.append("## Signals")
    lines.append("")
    for idx, m in enumerate(tracked[:signal_count], start=1):
        lines.append(f"### {idx}. {m.concept_label}")
        lines.append("")
        lines.append(f"**Momentum:** {_momentum_words(m.insider_momentum)} "
                     f"({m.insider_momentum:.3f})")
        lines.append("")
        lines.append(
            f"**Activity:** {m.mentions_24h} mentions in 24h, {m.mentions_7d} in 7d, "
            f"{m.mentions_30d} in 30d, from {m.unique_authors_7d} authors this week "
            f"(previous week: {m.unique_authors_prev_7d})."
        )
        lines.append("")
        lines.append(
            f"**Independent sources:** {m.independent_source_count} "
            f"(ratio {m.independence_ratio:.2f})."
            + (
                "  ⚠️ Low ratio — these voices share an origin, so this looks "
                "more like an echo than independent convergence."
                if m.independence_ratio < 0.5 and m.independent_source_count >= 2
                else ""
            )
        )
        lines.append("")
        if m.velocity_ratio is not None:
            lines.append(
                f"**Velocity:** {m.velocity_ratio:.2f}× a baseline of "
                f"{m.baseline_daily:.1f}/day."
            )
        else:
            lines.append(
                "**Velocity:** NOT COMPUTED — "
                f"only {m.baseline_days_available} days of history available."
            )
        lines.append("")
        lines.append(
            f"**Cross-platform:** {m.cross_platform_count} platforms, "
            f"{m.cross_role_count} evidence roles, {m.paper_count} papers."
        )
        lines.append("")
        lines.append(f"**Public search interest:** {m.google_search_change}")
        lines.append("")
        sources = _key_sources(db, m.concept_id)
        if sources:
            lines.append("**Recent sources:**")
            for src in sources:
                lines.append(f"- {src}")
            lines.append("")
        for note in m.notes:
            lines.append(f"> NOTE: {note}")
        if m.notes:
            lines.append("")
        lines.append("---")
        lines.append("")

    # -- nominations -------------------------------------------------------
    if nominated:
        lines.append("## Auto-nominated phrases (not yet tracked)")
        lines.append("")
        lines.append(
            "Phrases the system saw spreading across independent authors that "
            "are not in the concept registry. They are measured but excluded "
            "from editorial discovery until you promote them in "
            "`config/concepts.yaml` — the system does not get to decide on its "
            "own what is worth spending on."
        )
        lines.append("")
        for m in sorted(nominated, key=lambda x: x.insider_momentum, reverse=True)[:12]:
            lines.append(
                f"- **{m.concept_label}** — {m.mentions_7d} mentions/7d, "
                f"{m.unique_authors_7d} authors, "
                f"{m.independent_source_count} independent sources"
            )
        lines.append("")
        lines.append("---")
        lines.append("")

    # -- editorial candidates ---------------------------------------------
    if result.finalists:
        lines.append("## Editorial candidates")
        lines.append("")
        for idx, f in enumerate(result.finalists, start=1):
            c = f.candidate
            lines.append(f"### {idx}. {c.working_title}")
            lines.append("")
            lines.append(f"**Central question:** {c.central_question}")
            lines.append("")
            lines.append(f"**Premise:** {c.one_sentence_premise}")
            lines.append("")
            lines.append(f"**Why now:** {c.why_now}")
            lines.append("")
            lines.append(f"**Mental model shift:** {c.old_mental_model} → {c.new_mental_model}")
            lines.append("")
            lines.append(f"**Human stake:** {c.human_consequence}")
            lines.append("")
            lines.append(f"**Disagreement:** {c.credible_disagreement}")
            lines.append("")
            if f.opportunity:
                lines.append(f"**Opportunity score:** {f.opportunity.explain()}")
                lines.append("")
                for note in f.opportunity.notes:
                    lines.append(f"> {note}")
                if f.opportunity.notes:
                    lines.append("")
            if f.evaluation:
                lines.append(
                    f"**Evaluator mean:** {f.evaluation.mean_score():.1f}/10 · "
                    f"cares-before-jargon: "
                    f"{'YES' if f.evaluation.cares_before_knowing_term else 'NO'} · "
                    f"interests-non-AI: "
                    f"{'YES' if f.evaluation.interests_non_ai_person else 'NO'}"
                )
                lines.append("")
                lines.append(f"**Likeliest failure:** {f.evaluation.strongest_failure_reason}")
                lines.append("")
            if f.pairwise_record:
                lines.append(f"**Pairwise record:** {f.pairwise_record}")
                lines.append("")
            serious = [r for r in f.red_team if r.verdict in ("WOUNDED", "FATAL")]
            if serious:
                lines.append("**Red team:**")
                for r in serious[:4]:
                    lines.append(f"- [{r.attack_key}] {r.verdict} ({r.severity}/10): {r.argument}")
                lines.append("")
            lines.append(f"**Sources:** {len(c.source_ids)} items")
            lines.append("")
            lines.append("---")
            lines.append("")

    if result.cost:
        lines.append("## Run cost")
        lines.append("")
        for key, value in result.cost.items():
            if key != "failures":
                lines.append(f"- {key}: {value}")
        lines.append("")

    path.write_text("\n".join(lines))
    return path


def write_run_summary(db: Database, result: DiscoveryResult, runs_dir: Path) -> Path:
    """A short, human-readable account of what this run concluded."""
    out_dir = runs_dir / result.run_id
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "run_summary.md"
    today = datetime.now(timezone.utc).strftime("%B %d, %Y")

    lines = [f"# Frontier Scout — {today}", "", f"Run `{result.run_id}`", ""]

    if result.clusters:
        strongest = max(result.clusters, key=lambda c: c.momentum)
        lines += [
            "## Strongest emerging cluster",
            "",
            f"**{strongest.cluster_name}**",
            "",
            strongest.underlying_change,
            "",
            f"Surface terms: {', '.join(strongest.raw_terms[:8])}",
            "",
        ]
        if strongest.breadth_warning:
            lines += ["> ⚠️ The clusterer flagged this as possibly too broad.", ""]

    if result.finalists:
        top = result.finalists[0]
        lines += [
            "## Top candidate",
            "",
            f"### {top.candidate.working_title}",
            "",
            f"**Central question:** {top.candidate.central_question}",
            "",
            f"**Why now:** {top.candidate.why_now}",
            "",
        ]
        if len(result.finalists) > 1:
            lines += ["## Runners-up", ""]
            for f in result.finalists[1:4]:
                score = f.opportunity.value if f.opportunity else 0.0
                lines.append(f"- **{f.candidate.working_title}** ({score:.3f}) — "
                             f"{f.candidate.central_question}")
            lines.append("")

    lines += ["## Pipeline", ""]
    lines += [
        f"- concepts scored: {len(result.metrics)}",
        f"- groups through the gate: {len(result.groups)}",
        f"- scout signals: {len(result.signals)}",
        f"- clusters: {len(result.clusters)}",
        f"- candidates: {len(result.candidates)}",
        f"- evaluations: {len(result.evaluations)}",
        f"- pairwise judgements: "
        f"{len(result.tournament.results) if result.tournament else 0}",
        f"- red team findings: {len(result.red_team)}",
        "",
    ]

    fetches = db.conn.execute(
        "SELECT connector, status, COUNT(*) n FROM source_fetches"
        " GROUP BY connector, status ORDER BY connector",
    ).fetchall()
    if fetches:
        lines += ["## Source availability", ""]
        for row in fetches:
            marker = "" if row["status"] in ("OK", "PARTIAL") else "  ⚠️"
            lines.append(f"- {row['connector']}: {row['status']} ({row['n']}){marker}")
        lines.append("")

    path.write_text("\n".join(lines))
    return path
